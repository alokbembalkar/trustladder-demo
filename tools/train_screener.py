"""
Train the Stage 1 screening model, and measure what it can and cannot see.

    .venv/bin/python tools/train_screener.py

Everything here is generated by this repository. No real bills, no bought dataset,
no pretrained weights. The six renderers in `trustladder/bills.py` produce the
corpus, and because each bill is built to order its label is known by construction
rather than annotated by hand.

What the run reports, and why the second number matters more than the first
---------------------------------------------------------------------------
    EDITED      genuine bills vs bills altered after issue
    FABRICATED  genuine bills vs bills typed from a blank page

The first should be high. The second should be close to 0.50, which is chance.

That is not a bug in the model or in the training. `render_fabricated` calls
`render_genuine`: a fabricated bill is built exactly the way a real one is, because
a careful forger's output is exactly that. There is no artefact in the file to find,
so no model trained on files can find one, and a model that appeared to would be
learning a quirk of our generator rather than anything about fraud.

Which is the whole argument. A screening model cannot tell you whether a hospital
issued a bill. Only the hospital can. That is why `decide.py` never lets screening
clear a document, and why the issuer registry exists.

Output: trustladder/screener.json — feature names, coefficients, scaling, the chosen
threshold and these measurements, in plain text.
"""

from __future__ import annotations

import json
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

from trustladder.bills import (render_altered, render_discount_resaved, render_fabricated,
                               render_genuine, render_resaved)
from trustladder.cases import HOSPITALS
from trustladder.models import BillFields, LineItem
from trustladder.reader import read_bill
from trustladder.screener import features

N_PER_CLASS = 400
ITEMS = [("Room charges (semi-private)", 2400000), ("Surgeon fee", 5500000),
         ("Pharmacy and consumables", 1825000), ("Laboratory investigations", 640000)]


def a_bill(rng: random.Random, n: int) -> BillFields:
    """One plausible hospital bill. Amounts and dates vary; the shape does not."""
    issuer = rng.choice(list(HOSPITALS))
    name, _, prefix, bill_prefix = HOSPITALS[issuer]
    items = [LineItem(d, int(a * rng.uniform(0.6, 1.6)) // 100 * 100) for d, a in ITEMS]
    ticket = f"{prefix}-" + "-".join(
        "".join(rng.choice("23456789ABCDEFGHJKMNPQRSTUVWXYZ") for _ in range(4)) for _ in range(4))
    return BillFields(issuer, name, f"{bill_prefix}/2026/{900000 + n:06d}",
                      f"2026-{rng.randint(1, 9):02d}-{rng.randint(1, 28):02d}",
                      f"Patient {n}", items, sum(i.amount_paise for i in items), ticket)


def corpus() -> tuple[list[dict], list[int], list[str]]:
    """Generate the labelled set. 1 = the document was edited after it was issued."""
    rng = random.Random(20261015)
    rows, labels, kinds = [], [], []

    def add(pdf: bytes, label: int, kind: str):
        rows.append(features(pdf, read_bill(pdf)[1]))
        labels.append(label)
        kinds.append(kind)

    for n in range(N_PER_CLASS):
        b = a_bill(rng, n)
        joined = True
        # --- not edited -------------------------------------------------------
        add(render_genuine(b, joined=joined), 0, "genuine")
        # a genuine bill a phone app re-saved. The trap: it LOOKS touched and is not.
        add(render_resaved(b, joined=joined), 0, "genuine_resaved")
        # a genuine bill with a discount applied, re-saved. The wrongful-hold case.
        add(render_discount_resaved(b), 0, "genuine_discounted")
        # --- edited after issue ----------------------------------------------
        raised = b.total_paise + 100 * rng.randrange(15000, 90000, 500)
        add(render_altered(b, raised, joined=joined), 1, "altered")
        # --- fraud with nothing to detect ------------------------------------
        # typed from a blank page: held out of training, measured separately
        add(render_fabricated(b, joined=joined), 1, "fabricated")
    return rows, labels, kinds


def main() -> None:
    rows, labels, kinds = corpus()
    names = sorted(rows[0])
    X = np.array([[r[n] for n in names] for r in rows], dtype=float)
    y = np.array(labels)
    kinds = np.array(kinds)

    # Fabricated bills are NOT trained on. There is nothing in them to learn, and
    # including them would only teach the model our generator's noise.
    train_mask = kinds != "fabricated"
    Xtr_all, ytr_all = X[train_mask], y[train_mask]
    Xtr, Xte, ytr, yte, _, kte = train_test_split(
        Xtr_all, ytr_all, kinds[train_mask], test_size=0.3, random_state=7, stratify=ytr_all)

    scaler = StandardScaler().fit(Xtr)
    model = LogisticRegression(max_iter=2000, class_weight="balanced")
    model.fit(scaler.transform(Xtr), ytr)

    def prob(rows_x):
        return model.predict_proba(scaler.transform(rows_x))[:, 1]

    auc_edited = roc_auc_score(yte, prob(Xte))

    # The measurement that matters: genuine bills versus bills typed from nothing.
    genuine = X[(kinds == "genuine")]
    fabricated = X[(kinds == "fabricated")]
    yy = np.r_[np.zeros(len(genuine)), np.ones(len(fabricated))]
    auc_fab = roc_auc_score(yy, prob(np.r_[genuine, fabricated]))

    threshold = 0.60
    caught = float((prob(X[kinds == "altered"]) >= threshold).mean())
    false_alarm = float((prob(X[np.isin(kinds, ["genuine", "genuine_resaved",
                                                "genuine_discounted"])]) >= threshold).mean())
    fab_caught = float((prob(fabricated) >= threshold).mean())

    spec = {
        "_comment": "Trained by tools/train_screener.py on bills this repository generates. "
                    "Logistic regression; apply by hand with the formula in screener.py.",
        "features": names,
        "coefficients": [float(c) for c in model.coef_[0]],
        "intercept": float(model.intercept_[0]),
        "mean": [float(m) for m in scaler.mean_],
        "scale": [float(s) for s in scaler.scale_],
        "threshold": threshold,
        "trained_on": {"bills": int(train_mask.sum()), "classes": sorted(set(kinds.tolist())),
                       "held_out_entirely": "fabricated"},
        "measured": {
            "auc_edited_vs_genuine": round(float(auc_edited), 3),
            "auc_fabricated_vs_genuine": round(float(auc_fab), 3),
            "edited_caught_at_threshold": round(caught, 3),
            "genuine_false_alarm_at_threshold": round(false_alarm, 3),
            "fabricated_caught_at_threshold": round(fab_caught, 3),
        },
    }
    out = Path(__file__).resolve().parent.parent / "trustladder" / "screener.json"
    out.write_text(json.dumps(spec, indent=2) + "\n")

    print(f"corpus: {len(rows)} bills, {train_mask.sum()} used for training")
    print()
    print(f"  EDITED      AUC {auc_edited:.3f}   genuine vs altered-after-issue")
    print(f"  FABRICATED  AUC {auc_fab:.3f}   genuine vs typed-from-a-blank-page")
    print()
    print(f"  at threshold {threshold}:  {caught:.0%} of edited bills flagged, "
          f"{false_alarm:.0%} of genuine bills wrongly flagged, "
          f"{fab_caught:.0%} of fabricated bills flagged")
    print()
    print(f"wrote {out.relative_to(out.parent.parent)}")


if __name__ == "__main__":
    main()
