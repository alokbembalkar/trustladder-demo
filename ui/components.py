def writer_line(r: LadderResult) -> None:
    """Under every reason: who wrote it. A reader is entitled to know whether a sentence
    was generated by a model or assembled from fixed text, without a switch to find."""
    if r.reason_writer == "model":
        who = r.models_used.get("reason", "a language model")
        st.markdown(f'<div class="tl-who"><span class="ai">AI</span> Reason written by the language '
                    f'model <b>{who}</b> from the evidence graph and the rule, then checked back '
                    f'against the verdict.</div>', unsafe_allow_html=True)
    else:
        st.markdown('<div class="tl-who">Reason assembled from fixed sentences: no language model '
                    'ran for this claim, or its draft failed the check-back and was discarded.</div>',
                    unsafe_allow_html=True)


