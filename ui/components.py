def agent_panel(r: LadderResult, pending: bool = False) -> None:
    """The evidence agent's account: the order it chose, why, and what came back."""
    if not r.agent_trace and not pending:
        return
    st.markdown("**How the evidence was gathered**")
    model = r.models_used.get("agent")
    if pending:
        st.markdown('<div class="tl-who">The evidence agent is still writing its account. The checks '
                    'below ran in the rule\'s fixed order; refresh in a moment for the agent\'s '
                    'order and its case note.</div>', unsafe_allow_html=True)
    elif model:
        st.markdown(f'<div class="tl-who"><span class="ai">AI</span> The evidence agent <b>{model}</b> '
                    'chose the order of these checks and gave its reason for each. Every check answers '
                    'from the same findings the rule weighed, so the account cannot differ from the '
                    'verdict; any check it skipped was run by the guard.</div>', unsafe_allow_html=True)
    else:
        st.markdown('<div class="tl-who">No agent ran for this claim: the checks ran in the rule\'s '
                    'fixed order.</div>', unsafe_allow_html=True)
    if r.agent_note:
        st.markdown(f'<div class="tl-note"><b>Case note.</b> {r.agent_note}</div>', unsafe_allow_html=True)
    rows = ""
    for s in r.agent_trace:
        by = s.get("by", "agent")
        rows += (f'<div class="tl-trace"><div class="n">{s.get("n", "")}</div><div class="body">'
                 f'<div class="h">{_TOOL_WORDS.get(s.get("tool"), s.get("tool"))} '
                 f'<span class="tl-chip" style="background:{_BY_COLOUR.get(by, "#475569")}">{by}</span></div>'
                 f'<div class="why">{s.get("why", "")}</div><div class="res">{s.get("result", "")}</div>'
                 f'</div></div>')
    st.markdown(rows, unsafe_allow_html=True)


