def reading_line(r: LadderResult) -> None:
    """How the bill was read, and how far that reading may be trusted."""
    rep = r.read_report or {}
    source = rep.get("source", "text layer")
    if source != "vision model":
        st.markdown('<div class="tl-who">Read from the PDF\'s text layer, exactly. No model was '
                    'needed to read this bill.</div>', unsafe_allow_html=True)
        return
    model = r.models_used.get("reader") or rep.get("model") or "the vision model"
    bits = [f'<span class="ai">AI</span> Read from a photograph by the vision model <b>{model}</b>']
    if rep.get("language"):
        bits.append(f"printed in <b>{rep['language']}</b>")
    if rep.get("customer_confirmed"):
        n = int(rep.get("corrections") or 0)
        bits.append("the customer confirmed the details" + (f" and corrected {n} field{'s' if n != 1 else ''}"
                                                            if n else ", no corrections"))
    if rep.get("second_reader"):
        agree = rep.get("agree")
        bits.append("the second reader (deep OCR) " + ("agreed" if agree else
                                                       "did not agree" if agree is False else "gave no opinion"))
    else:
        bits.append("no second reader on this deployment")
    verdict_note = ("corroborated: the issuer's word can clear or condemn it"
                    if rep.get("corroborated") else
                    "not corroborated: the issuer's word can clear it, but a contradiction asks "
                    "for the original instead of condemning")
    st.markdown(f'<div class="tl-who">{" · ".join(bits)}.<br>{verdict_note}.</div>',
                unsafe_allow_html=True)


