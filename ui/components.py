def model_card() -> None:
    """Publish the screening model the way the rule is published.

    The product's promise is that a decision can be read by the person it affects.
    A model that nobody can inspect would sit badly beside a rule printed on a slide,
    so the model is printed too: what it looks at, how much weight it gives each
    thing, and what it measurably can and cannot do.
    """
    model = screener.load()
    if model is None:
        st.caption("This build ships without a trained screening model.")
        return

    st.markdown("**The screening model.** Trained by us on "
                f"{model.trained_on.get('bills', 0):,} bills this project generates. It never decides "
                "anything: it reports, and the rule above weighs what it reports.")

    weights = sorted(zip(model.names, model.coef), key=lambda kv: -abs(kv[1]))
    rows = "".join(
        f"<tr><td>{_PLAIN_FEATURE.get(n, n)}</td>"
        f"<td style='text-align:right'>{w:+.2f}</td>"
        f"<td style='color:#64748B'>{'points to an edit' if w > 0.05 else 'the model learned to ignore this'}</td></tr>"
        for n, w in weights)
    st.markdown(
        "<table style='width:100%;border-collapse:collapse;font-size:0.88rem'>"
        "<tr style='text-align:left;border-bottom:1px solid #CBD5E1'>"
        "<th>What it looks at</th><th style='text-align:right'>Weight</th><th>Meaning</th></tr>"
        f"{rows}</table>", unsafe_allow_html=True)
    st.caption("Look at the bottom of that list. The checks written by hand treat a re-saved file as "
               "evidence; the model, left to learn for itself, gave those signals almost no weight and "
               "leaned on the two things only a real edit produces: a new typeface, and a total that no "
               "longer matches the charges.")

    m = model.measured
    st.write("")
    kpis([(f"{m.get('edited_caught_at_threshold', 0):.0%}", "of bills edited after issue, flagged"),
          (f"{m.get('genuine_false_alarm_at_threshold', 0):.0%}",
           "of genuine bills wrongly flagged<br>the written checks flag every re-saved one"),
          (f"{m.get('auc_fabricated_vs_genuine', 0):.2f}",
           "on bills typed from a blank page<br>0.50 is chance: it cannot see them at all")])
    st.caption("The last number is the one to read twice. A bill typed from nothing was never edited, "
               "so there is no trace in the file and no model can find one. That is not a gap to train "
               "away: it is the reason no screening signal is ever allowed to clear a document, and the "
               "reason the issuer registry exists.")


